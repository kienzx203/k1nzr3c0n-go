package store

// translateSchema rewrites the SQLite DDL the package defines into PostgreSQL.
// Keeping one source of truth (the SQLite schema constants) and translating at
// open time avoids maintaining two parallel copies of ~37 CREATE TABLEs.
//
// The k1z DDL vocabulary is small and regular, so the rules are few:
//
//   - `INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT` -> an IDENTITY column. BY
//     DEFAULT (not ALWAYS) so the few explicit-id inserts (e.g. the id=1
//     singleton rows) still work. Any trailing CHECK(...) is preserved.
//   - `DATETIME` -> TEXT. The store already serializes time as text via SqlTime
//     and parses it via parseDBTime, so TEXT columns behave exactly as under
//     SQLite; native TIMESTAMPTZ would change what the driver hands Scan.
//   - `DEFAULT CURRENT_TIMESTAMP` -> a to_char(now()) expression producing the
//     very format ParseTime expects, so DB-defaulted timestamps round-trip.
//   - on BOOLEAN columns, the numeric `DEFAULT 0`/`DEFAULT 1` become FALSE/TRUE
//     (PostgreSQL booleans reject 0/1 as a default); INTEGER defaults are left.
//   - `ALTER TABLE ... ADD COLUMN` -> `ADD COLUMN IF NOT EXISTS`, since the
//     idempotent migrations rely on re-running harmlessly.

import "strings"

// pgTimestampDefault reproduces SqlTime's layout ("2006-01-02 15:04:05.999999",
// naive UTC) as a server-side default, so a row inserted without an explicit
// timestamp still parses back through ParseTime.
const pgTimestampDefault = `DEFAULT to_char((now() AT TIME ZONE 'utc'), 'YYYY-MM-DD HH24:MI:SS.US')`

func translateSchema(ddl string) string {
	// Column/constraint rewrites that are safe to apply across the whole blob.
	ddl = strings.ReplaceAll(ddl,
		"INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT",
		"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
	ddl = strings.ReplaceAll(ddl, "DEFAULT CURRENT_TIMESTAMP", pgTimestampDefault)

	// The remaining rewrites are line-local because they depend on the column
	// type on that line (DATETIME -> TEXT everywhere; boolean default fix only on
	// BOOLEAN lines).
	lines := strings.Split(ddl, "\n")
	for i, ln := range lines {
		if strings.Contains(ln, "DATETIME") {
			ln = strings.ReplaceAll(ln, "DATETIME", "TEXT")
		}
		if strings.Contains(ln, "BOOLEAN") {
			ln = strings.ReplaceAll(ln, "DEFAULT 0", "DEFAULT FALSE")
			ln = strings.ReplaceAll(ln, "DEFAULT 1", "DEFAULT TRUE")
		}
		if strings.Contains(ln, "INSERT OR IGNORE") {
			ln = pgInsertIgnore(ln)
		}
		lines[i] = ln
	}
	return strings.Join(lines, "\n")
}

// pgInsertIgnore converts a single SQLite `INSERT OR IGNORE INTO …` statement to
// the PostgreSQL `INSERT INTO … ON CONFLICT DO NOTHING` form. A bare ON CONFLICT
// (no target) ignores a conflict on any unique/primary-key constraint, which
// matches INSERT OR IGNORE's semantics. The clause goes before a trailing `;`.
func pgInsertIgnore(stmt string) string {
	stmt = strings.Replace(stmt, "INSERT OR IGNORE", "INSERT", 1)
	if i := strings.LastIndex(stmt, ";"); i >= 0 {
		return stmt[:i] + " ON CONFLICT DO NOTHING" + stmt[i:]
	}
	return stmt + " ON CONFLICT DO NOTHING"
}

// translateMigration rewrites a single idempotent ALTER statement for PostgreSQL:
// the column-level rules plus ADD COLUMN IF NOT EXISTS (SQLite has no IF NOT
// EXISTS there and instead relies on the caller ignoring the duplicate-column
// error; PostgreSQL supports the clause directly).
func translateMigration(stmt string) string {
	stmt = translateSchema(stmt)
	stmt = strings.Replace(stmt, "ADD COLUMN ", "ADD COLUMN IF NOT EXISTS ", 1)
	return stmt
}

// ddl returns schema DDL in the store's active dialect.
func (s *Store) ddl(sqliteDDL string) string {
	if s.db.dia == dialectPostgres {
		return translateSchema(sqliteDDL)
	}
	return sqliteDDL
}

// migration returns an ALTER statement in the store's active dialect.
func (s *Store) migration(stmt string) string {
	if s.db.dia == dialectPostgres {
		return translateMigration(stmt)
	}
	return stmt
}
